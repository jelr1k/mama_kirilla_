def command_definition_display(command_id: str) -> list[str]:
    return list(ROUTER_COMMANDS.get(command_id, {}).get("display", []))


def match_command_definition(command_id: str, text: str) -> re.Match | None:
    definition = ROUTER_COMMANDS.get(command_id)
    if not definition:
        return None
    patterns = definition.get("patterns")
    if patterns is None:
        pattern = definition.get("pattern")
        patterns = [pattern] if pattern else []
    for pattern in patterns:
        match = re.fullmatch(pattern, text, flags=re.IGNORECASE)
        if match:
            return match
    return None
