_ICON_CACHE: dict[tuple[str, str, int], QIcon] = {}


def get_icon(name: str, color: str = "#00e5ff", size: int = 18) -> QIcon:
    """Генерирует и кэширует векторную QIcon из SVG шаблона."""
    cache_key = (name, color, size)
    if cache_key in _ICON_CACHE:
        return _ICON_CACHE[cache_key]

    template = SVG_TEMPLATES.get(name)
    if not template:
        logger.debug("Icon template not found: %s", name)
        return QIcon()

    try:
        svg_code = template.format(color=color)
        renderer = QSvgRenderer(QByteArray(svg_code.encode("utf-8")))
        if not renderer.isValid():
            return QIcon()

        pixmap = QPixmap(size, size)
        pixmap.fill(Qt.GlobalColor.transparent)
        painter = QPainter(pixmap)
        renderer.render(painter)
        painter.end()

        icon = QIcon(pixmap)
        _ICON_CACHE[cache_key] = icon
        return icon
    except Exception as exc:
        logger.debug("Failed to create icon %s: %s", name, exc)
        return QIcon()
